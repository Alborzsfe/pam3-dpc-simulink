function build_pam3_models()
% Author both models using documented Simulink APIs, in the user's MATLAB.
root = fileparts(mfilename('fullpath'));
addpath(fullfile(root, 'matlab'));
addpath(fullfile(root, 'models'));
load_system('simulink');
if ~evalin('base', 'exist(''pam3_cfg'', ''var'')')
    assignin('base', 'pam3_cfg', pam3_config());
end
if ~evalin('base', 'exist(''pam3_stop_time'', ''var'')')
    initial_cfg = pam3_config();
    assignin('base', 'pam3_stop_time', 100 * initial_cfg.sample_time);
end
lib = 'pam3_patent_blocks'; model = 'pam3_patent_demo';
if bdIsLoaded(lib)
    close_system(lib, 0);
end
if bdIsLoaded(model)
    close_system(model, 0);
end
new_system(lib, 'Library');
add_block('built-in/M-S-Function', [lib '/PAM3_Decoder'], ...
    'FunctionName', 'pam3_sfun', 'Parameters', 'pam3_cfg', ...
    'Position', [80, 70, 290, 180]);
add_block('built-in/M-S-Function', [lib '/Host_Record_Packer'], ...
    'FunctionName', 'pam3_packer_sfun', 'Parameters', 'pam3_cfg', ...
    'Position', [380, 70, 610, 180]);
save_system(lib, fullfile(root, 'models', [lib '.slx']));
set_param(lib, 'Lock', 'on');

new_system(model);
set_param(model, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', ...
    'FixedStep', 'pam3_cfg.sample_time', 'StartTime', '0', ...
    'StopTime', 'pam3_stop_time', 'SimulationMode', 'normal', ...
    'ReturnWorkspaceOutputs', 'on', 'SaveTime', 'off', ...
    'SaveOutput', 'off', 'SignalLogging', 'off');
set_param(model, 'InitFcn', ['pam3_project_root = fileparts(fileparts(get_param(bdroot,''FileName''))); ' ...
    'addpath(pam3_project_root,fullfile(pam3_project_root,''matlab'')); pam3_prepare_model;']);
names = {'ADC_Master', 'ADC_Slave', 'Acquisition_Command'};
variables = {'pam3_input_master', 'pam3_input_slave', 'pam3_command'};
ys = [90, 325, 560];
for k = 1:3
    add_block('simulink/Sources/From Workspace', [model '/' names{k}], ...
        'VariableName', variables{k}, 'Interpolate', 'off', ...
        'SampleTime', 'pam3_cfg.sample_time', ...
        'OutputAfterFinalValue', 'Holding final value', ...
        'Position', [45, ys(k), 225, ys(k)+45]);
end
add_block([lib '/PAM3_Decoder'], [model '/Master_Decoder'], ...
    'Position', [330, 75, 580, 215]);
add_block([lib '/PAM3_Decoder'], [model '/Slave_Decoder'], ...
    'Position', [330, 310, 580, 450]);
add_block([lib '/Host_Record_Packer'], [model '/Host_Record_Packer'], ...
    'Position', [760, 185, 985, 360]);
add_block('simulink/Sinks/To Workspace', [model '/Master_Trace'], ...
    'VariableName', 'trace_master', 'SaveFormat', 'Structure With Time', ...
    'MaxDataPoints', 'inf', 'Position', [760, 60, 970, 110]);
add_block('simulink/Sinks/To Workspace', [model '/Slave_Trace'], ...
    'VariableName', 'trace_slave', 'SaveFormat', 'Structure With Time', ...
    'MaxDataPoints', 'inf', 'Position', [760, 440, 970, 490]);
add_block('simulink/Sinks/To Workspace', [model '/Host_Records'], ...
    'VariableName', 'trace_host', 'SaveFormat', 'Structure With Time', ...
    'MaxDataPoints', 'inf', 'Position', [1080, 230, 1280, 285]);
add_block('simulink/Sinks/Scope', [model '/ADC_Waveforms'], ...
    'NumInputPorts', '2', 'Position', [330, 555, 410, 610]);
add_line(model, 'ADC_Master/1', 'Master_Decoder/1', 'autorouting', 'on');
add_line(model, 'ADC_Slave/1', 'Slave_Decoder/1', 'autorouting', 'on');
add_line(model, 'Acquisition_Command/1', 'Master_Decoder/2', 'autorouting', 'on');
add_line(model, 'Acquisition_Command/1', 'Slave_Decoder/2', 'autorouting', 'on');
add_line(model, 'Master_Decoder/1', 'Master_Trace/1', 'autorouting', 'on');
add_line(model, 'Slave_Decoder/1', 'Slave_Trace/1', 'autorouting', 'on');
add_line(model, 'Master_Decoder/1', 'Host_Record_Packer/1', 'autorouting', 'on');
add_line(model, 'Slave_Decoder/1', 'Host_Record_Packer/2', 'autorouting', 'on');
add_line(model, 'Acquisition_Command/1', 'Host_Record_Packer/3', 'autorouting', 'on');
add_line(model, 'Host_Record_Packer/1', 'Host_Records/1', 'autorouting', 'on');
add_line(model, 'ADC_Master/1', 'ADC_Waveforms/1', 'autorouting', 'on');
add_line(model, 'ADC_Slave/1', 'ADC_Waveforms/2', 'autorouting', 'on');
annotation = Simulink.Annotation(model, sprintf(['US11405248B2 - complete documented digital reconstruction\n' ...
    'Each decoder: DC -> slope/four thresholds -> spike -> edges/must -> timing -> symbol\n' ...
    'Source boundary: paired 8-bit ADC samples. Host records: 128 bits/channel.\n' ...
    'command 1=data, 2=20-position tail flush, 0=idle, 3=reset.\n' ...
    'Normal-mode MATLAB S-functions; no physical ADC/USB or FPGA timing claim.']));
annotation.Position = [45, 660];
save_system(model, fullfile(root, 'models', [model '.slx']));
fprintf('Models saved under %s\n', fullfile(root, 'models'));
end
