function dpc3_noise_export_summary(manifest,folder)
% Check provenance BEFORE creating any report files.
for k = 1:numel(manifest)
    e = manifest{k};
    assert(e.binary_limit_report.passed && e.binary_limit_report.simulink_executed, ...
        'DPC3:Provenance','Summary requires the actual full-plant binary-limit proof.');
    for r = {e.conventional,e.proposed}
        assert(r{1}.simulink_executed && r{1}.closed_loop_executed && ...
            r{1}.info.stimulus_verification.passed,'DPC3:Provenance', ...
            'Summary requires actual converter runs and stimulus verification.');
    end
end
if ~exist(folder,'dir'),mkdir(folder);end
file = fopen(fullfile(folder,'noise_comparison_metrics.csv'),'w');assert(file >= 0);
close_csv = onCleanup(@() fclose(file));
fprintf(file,['case_id,seed,control_Fs_Hz,method,THD_a_percent,THD_b_percent,THD_c_percent,' ...
    'current_a_nonfundamental_percent,P_true_mean_W,P_true_ripple_pp_W,P_true_ripple_rms_W,' ...
    'P_true_tracking_RMSE_W,Q_true_mean_var,Q_true_ripple_pp_var,Q_true_ripple_rms_var,' ...
    'Q_true_tracking_RMSE_var,Vdc_mean_V,Vdc_error_percent,mean_equivalent_fsw_Hz,' ...
    'P_feedback_error_RMSE_W,Q_feedback_error_RMSE_var,grid_voltage_THD_a_percent,' ...
    'zero_fraction_p,zero_fraction_q,guard_fraction,stationary_window,binary_limit_passed\n']);
delta = fopen(fullfile(folder,'paired_changes_percent.csv'),'w');assert(delta >= 0);
close_delta = onCleanup(@() fclose(delta));
fprintf(delta,['case_id,seed,control_Fs_Hz,THD_a_change_percent,P_true_ripple_RMS_change_percent,' ...
    'P_true_tracking_RMSE_change_percent,Q_true_tracking_RMSE_change_percent,fsw_change_percent\n']);
report = fopen(fullfile(folder,'READ_RESULTS.md'),'w');assert(report >= 0);
close_report = onCleanup(@() fclose(report));
fprintf(report,['# Actual Simulink noise/distortion study\n\n' ...
    'Results are appended only after native converter simulations, stimulus checks and the ' ...
    'bit-exact full-plant binary-limit test pass. Completed pairs only; the run may still be partial.\n\n' ...
    'Noise is injected after 0.3 s by default; FFT/metrics use 0.6..0.8 s. ' ...
    'P/Q ripple and tracking use TRUE power calculated from physical voltage/current. ' ...
    'Sensor error is reported separately. Harmonic THD covers orders 2..50; ' ...
    'the nonfundamental residual also includes broadband noise/interharmonics.\n\n' ...
    '| Case | Seed | Fs kHz | THD a conventional / ternary %% | True P RMS ripple W | Binary limit |\n' ...
    '|---|---|---|---|---|---|\n']);
for k = 1:numel(manifest)
    e = manifest{k}; pair = {e.conventional,e.proposed};
    assert(e.binary_limit_report.passed && e.binary_limit_report.simulink_executed);
    for j = 1:2
        r = pair{j}; m = r.metrics;
        assert(r.simulink_executed && r.closed_loop_executed && r.info.stimulus_verification.passed);
        a = [r.fft{1}.thd_percent,r.fft{2}.thd_percent,r.fft{3}.thd_percent, ...
            m.current_nonfundamental_percent(1),m.p.mean,m.p.peak_to_peak,m.p.ripple_rms,m.p_tracking_rmse, ...
            m.q.mean,m.q.peak_to_peak,m.q.ripple_rms,m.q_tracking_rmse,m.vdc.mean, ...
            m.dc_tracking_error_percent,m.mean_equivalent_switching_hz, ...
            m.p_feedback_noise_rmse,m.q_feedback_noise_rmse,m.grid_voltage_thd_percent(1), ...
            r.zero_fraction_p,r.zero_fraction_q,r.guard_fraction,m.stationary_window,e.binary_limit_report.passed];
        fprintf(file,'%s,%u,%.12g,%s',e.case_id,e.seed,e.control_hz,r.info.method);
        fprintf(file,',%.12g',a);fprintf(file,'\n');
    end
    a = pair{1}; b = pair{2};
    changes = [change(a.fft{1}.thd_percent,b.fft{1}.thd_percent), ...
        change(a.metrics.p.ripple_rms,b.metrics.p.ripple_rms), ...
        change(a.metrics.p_tracking_rmse,b.metrics.p_tracking_rmse), ...
        change(a.metrics.q_tracking_rmse,b.metrics.q_tracking_rmse), ...
        change(a.metrics.mean_equivalent_switching_hz,b.metrics.mean_equivalent_switching_hz)];
    fprintf(delta,'%s,%u,%.12g',e.case_id,e.seed,e.control_hz);fprintf(delta,',%.12g',changes);fprintf(delta,'\n');
    fprintf(report,'| %s | %u | %g | %.4g / %.4g | %.4g / %.4g | PASS |\n', ...
        e.case_id,e.seed,e.control_hz/1000,a.fft{1}.thd_percent,b.fft{1}.thd_percent, ...
        a.metrics.p.ripple_rms,b.metrics.p.ripple_rms);
end
fprintf(report,['\nIn paired_changes_percent.csv, negative means a decrease and positive an increase. ' ...
    'There is no automatic claim that ternary is better. When the baseline value is essentially zero, change is NaN. ' ...
    'The prediction guard is a one-step model comparison, not a guarantee of closed-loop THD or ripple. ' ...
    'The predictor retains its balanced fundamental rotating-voltage assumption under distortion; ' ...
    'this model mismatch is deliberately part of the robustness test.\n\n' ...
    'One seed is a pilot comparison, not statistical evidence. Add independent noise_seeds for repeated trials. ' ...
    'The 200-kHz fixed sensor-noise clock is common to both control rates; sensor anti-alias filtering is not added. ' ...
    'Inspect stationary_window, DC regulation and all three current phases before interpreting improvements.\n']);
end
function d = change(a,b)
if abs(a) < 1e-10, d = NaN; else, d = 100*(b-a)/abs(a); end
end
