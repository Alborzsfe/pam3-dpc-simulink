function [raw,coverage]=PAM3_LOG_COVERAGE(raw,cfg,actualStop)
% Validate full periodic logs before allowing their final held interval.
validateattributes(cfg.Ts,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(cfg.stopTime,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(actualStop,{'numeric'},{'scalar','real','finite'});
tol=min(cfg.Ts/1e6,64*eps(max(1,abs(cfg.stopTime))));
assert(abs(actualStop-cfg.stopTime)<=tol,'PAM3Study:IncompleteSimulation', ...
    'Simulation ended at %.17g s; expected %.17g s.',actualStop,cfg.stopTime);
labels=fieldnames(raw);rows=cell(numel(labels),1);
assert(~isempty(labels),'PAM3Study:EmptyLogs','No study logs were returned.');
for k=1:numel(labels)
    label=labels{k};s=raw.(label);
    assert(isstruct(s) && isfield(s,'time') && isfield(s,'signals') && ...
        isfield(s.signals,'values'),'PAM3Study:LogFormat','Invalid log for %s.',label);
    t=double(s.time(:));
    assert(~isempty(t) && all(isfinite(t)) && all(diff(t)>=0), ...
        'PAM3Study:LogTime','Empty, nonfinite or decreasing log time for %s.',label);
    assert(~isempty(s.signals.values) && mod(numel(s.signals.values),numel(t))==0, ...
        'PAM3Study:LogShape','Time/value sizes do not match for %s.',label);
    assert(all(isfinite(s.signals.values(:))),'PAM3Study:LogValues', ...
        'Nonfinite values in %s; no missing data were filled.',label);
    tu=unique(t);gap=0;
    if numel(tu)>1,gap=max(diff(tu));end
    % End-exclusive acquisition: a final hit at StopTime is optional. Every
    % interval before it must be covered. Missing full ticks are rejected.
    assert(abs(tu(1))<=tol && tu(end)<=actualStop+tol && ...
        tu(end)+cfg.Ts>=actualStop-tol && gap<=cfg.Ts+tol, ...
        'PAM3Study:LogCoverage', ...
        ['Incomplete %s log: first=%.17g, last=%.17g, max gap=%.17g s; ' ...
         'required start=0, stop=%.17g, period=%.17g s. ' ...
         'Check logging settings and free space; no missing data were filled.'], ...
         label,tu(1),tu(end),gap,actualStop,cfg.Ts);
    s.pam3Logging=struct('Verified',true,'SampleTime',cfg.Ts,'StopTime',actualStop);
    raw.(label)=s;
    rows{k}=struct('Signal',string(label),'Samples',numel(tu), ...
        'FirstTime_s',tu(1),'LastTime_s',tu(end),'MaxGap_s',gap, ...
        'SimulationStop_s',actualStop,'SampleTime_s',cfg.Ts, ...
        'FinalIntervalHeld',tu(end)<actualStop-tol);
end
coverage=struct2table(vertcat(rows{:}));
end
