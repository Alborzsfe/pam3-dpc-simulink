function build_dpc_replay_model(cfg)
% Native Simulink builder. Ternary adapter contains visible ordinary blocks.
root = fileparts(mfilename('fullpath'));
addpath(fullfile(root, 'matlab'), fullfile(root, 'patent_core'));
if nargin == 0, cfg = dpc_config(); end
dpc_validate_config(cfg);
load_system('simulink');
model = 'dpc_same_input_comparison';
if bdIsLoaded(model), close_system(model, 0); end
new_system(model);
set_param(model, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', ...
    'FixedStep', 'dpc_replay_cfg.sample_time', 'StartTime', '0', ...
    'StopTime', 'dpc_replay_stop', 'ReturnWorkspaceOutputs', 'on', ...
    'SaveTime', 'off', 'SaveOutput', 'off', 'SignalLogging', 'off', ...
    'SimulationMode', 'normal');
set_param(model, 'InitFcn', ['dpc_project_root = fileparts(fileparts(get_param(bdroot,''FileName''))); ' ...
    'addpath(dpc_project_root,fullfile(dpc_project_root,''matlab''),' ...
    'fullfile(dpc_project_root,''patent_core'')); dpc_prepare_replay_model;']);
for channel = 1:2
    label = cfg.channels{channel}; y = 60+(channel-1)*390;
    add_source(model, ['Error_' label], ['dpc_error_' label], [40, y, 215, y+45]);
    add_source(model, ['ADC_' label], ['dpc_adc_' label], [40, y+195, 215, y+240]);
    add_block('simulink/Discontinuities/Relay', [model '/Binary_' label], ...
        'OnSwitchValue', number(cfg.relay_on(channel)), ...
        'OffSwitchValue', number(cfg.relay_off(channel)), ...
        'OnOutputValue', number(cfg.relay_output_on(channel)), ...
        'OffOutputValue', number(cfg.relay_output_off(channel)), ...
        'SampleTime', 'dpc_replay_cfg.sample_time', ...
        'Position', [320, y, 490, y+55]);
    subsystem = [model '/Control_Ternary_' label];
    add_block('built-in/Subsystem', subsystem, 'Position', [320, y+90, 535, y+155]);
    create_ternary_subsystem(subsystem, cfg, channel);
    add_block('built-in/M-S-Function', [model '/Patent_' label], ...
        'FunctionName', 'pam3_sfun', 'Parameters', 'dpc_patent_cfg', ...
        'Position', [320, y+195, 535, y+275]);
    add_sink(model, ['Binary_' label '_Log'], ['dpc_binary_' label], [660, y, 850, y+45]);
    add_sink(model, ['Ternary_' label '_Log'], ['dpc_ternary_' label], [660, y+90, 850, y+135]);
    add_sink(model, ['Patent_' label '_Log'], ['dpc_patent_' label], [660, y+215, 850, y+260]);
    add_line(model, ['Error_' label '/1'], ['Binary_' label '/1'], 'autorouting', 'on');
    add_line(model, ['Error_' label '/1'], ['Control_Ternary_' label '/1'], 'autorouting', 'on');
    add_line(model, ['ADC_' label '/1'], ['Patent_' label '/1'], 'autorouting', 'on');
    add_line(model, ['Binary_' label '/1'], ['Binary_' label '_Log/1'], 'autorouting', 'on');
    add_line(model, ['Control_Ternary_' label '/1'], ['Ternary_' label '_Log/1'], 'autorouting', 'on');
    add_line(model, ['Patent_' label '/1'], ['Patent_' label '_Log/1'], 'autorouting', 'on');
end
add_source(model, 'Capture_Command', 'dpc_command', [40, 835, 215, 880]);
add_line(model, 'Capture_Command/1', 'Patent_P/2', 'autorouting', 'on');
add_line(model, 'Capture_Command/1', 'Patent_Q/2', 'autorouting', 'on');
note = Simulink.Annotation(model, sprintf(['Same captured eP / eQ, three parallel routes.\n' ...
    'Binary: original relay thresholds and outputs.\n' ...
    'Control ternary: new two-relay adapter, neutral state, no gate connection.\n' ...
    'Patent: static ADC calibration + unchanged full PAM3 decoding pipeline.\n' ...
    'The patent has no native power-error or converter switching-table meaning.']));
note.Position = [40, 930];
save_system(model, fullfile(root, 'models', [model '.slx']));
fprintf('Built native comparison model: %s\n', model);
end

function add_source(model, name, variable, position)
add_block('simulink/Sources/From Workspace', [model '/' name], ...
    'VariableName', variable, 'Interpolate', 'off', ...
    'SampleTime', 'dpc_replay_cfg.sample_time', ...
    'OutputAfterFinalValue', 'Holding final value', 'Position', position);
end

function add_sink(model, name, variable, position)
add_block('simulink/Sinks/To Workspace', [model '/' name], ...
    'VariableName', variable, 'SaveFormat', 'Structure With Time', ...
    'MaxDataPoints', 'inf', 'Decimation', '1', 'Position', position);
end

function create_ternary_subsystem(path, cfg, channel)
center = (cfg.relay_on(channel)+cfg.relay_off(channel))/2;
h = (cfg.relay_on(channel)-cfg.relay_off(channel))/2;
release = cfg.release_ratio*h;
add_block('built-in/Inport', [path '/Error'], 'Position', [25, 108, 55, 122]);
add_block('simulink/Math Operations/Bias', [path '/Center_Error'], ...
    'Bias', number(-center), 'Position', [95, 95, 155, 135]);
add_block('simulink/Math Operations/Gain', [path '/Reverse_Sign'], ...
    'Gain', '-1', 'Position', [210, 165, 260, 205]);
add_block('simulink/Discontinuities/Relay', [path '/Positive_State'], ...
    'OnSwitchValue', number(h), 'OffSwitchValue', number(release), ...
    'OnOutputValue', '1', 'OffOutputValue', '0', ...
    'SampleTime', 'dpc_replay_cfg.sample_time', 'Position', [300, 45, 405, 95]);
add_block('simulink/Discontinuities/Relay', [path '/Negative_State'], ...
    'OnSwitchValue', number(h), 'OffSwitchValue', number(release), ...
    'OnOutputValue', '1', 'OffOutputValue', '0', ...
    'SampleTime', 'dpc_replay_cfg.sample_time', 'Position', [300, 165, 405, 215]);
add_block('simulink/Math Operations/Sum', [path '/Three_Level_Output'], ...
    'Inputs', '+-', 'Position', [465, 103, 485, 147]);
add_block('built-in/Outport', [path '/Decision'], 'Position', [545, 118, 575, 132]);
add_line(path, 'Error/1', 'Center_Error/1', 'autorouting', 'on');
add_line(path, 'Center_Error/1', 'Positive_State/1', 'autorouting', 'on');
add_line(path, 'Center_Error/1', 'Reverse_Sign/1', 'autorouting', 'on');
add_line(path, 'Reverse_Sign/1', 'Negative_State/1', 'autorouting', 'on');
add_line(path, 'Positive_State/1', 'Three_Level_Output/1', 'autorouting', 'on');
add_line(path, 'Negative_State/1', 'Three_Level_Output/2', 'autorouting', 'on');
add_line(path, 'Three_Level_Output/1', 'Decision/1', 'autorouting', 'on');
end

function text_value = number(value)
text_value = sprintf('%.17g', value);
end
