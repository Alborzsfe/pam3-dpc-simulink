function [adc, mapping] = dpc_map_adc(error_signal, cfg, channel)
% STATIC calibration: the relay -H/+H boundaries map to code 95/140.
% No TX labels, future statistics, or automatic whole-capture normalization.
lower = cfg.relay_off(channel); upper = cfg.relay_on(channel);
gain = (140 - 95) / (upper - lower);
offset = 95 - gain * lower;
x = double(error_signal(:));
assert(all(isfinite(x)));
unclipped = offset + gain * x;
adc = min(255, max(0, floor(unclipped + 0.5)));
mapping = struct('gain_codes_per_error_unit', gain, 'offset_codes', offset, ...
    'low_clipping_fraction', mean(unclipped < 0), ...
    'high_clipping_fraction', mean(unclipped > 255), ...
    'clipping_fraction', mean(unclipped < 0 | unclipped > 255), ...
    'error_at_code_0', -offset / gain, 'error_at_code_255', (255-offset)/gain, ...
    'thresholds_in_error_units', ([140, 95, 160, 80]-offset)/gain, ...
    'half_lsb_in_error_units', 0.5/gain);
end
