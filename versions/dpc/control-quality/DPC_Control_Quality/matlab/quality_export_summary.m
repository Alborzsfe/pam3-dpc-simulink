function quality_export_summary(results, folder)
for k = 1:numel(results)
    assert(results{k}.closed_loop_executed && results{k}.simulink_executed, ...
        'QUALITY:Provenance', 'Summary requires actual closed-loop simulations.');
end
if ~exist(folder, 'dir'), mkdir(folder); end
file = fopen(fullfile(folder, 'comparison_metrics.csv'), 'w'); assert(file >= 0);
cleanup_csv = onCleanup(@() fclose(file));
fprintf(file, ['control_Fs_Hz,method,THD_a_percent,THD_b_percent,THD_c_percent,' ...
    'P_mean_W,P_ripple_pp_W,P_ripple_rms_W,P_tracking_RMSE_W,' ...
    'Q_mean_var,Q_ripple_pp_var,Q_ripple_rms_var,Q_tracking_RMSE_var,' ...
    'Vdc_mean_V,Vdc_tracking_error_percent,mean_equivalent_fsw_Hz,' ...
    'current_RMS_drift_percent,Vdc_mean_drift_percent,stationary_window\n']);
report = fopen(fullfile(folder, 'READ_RESULTS.md'), 'w'); assert(report >= 0);
cleanup_report = onCleanup(@() fclose(report));
fprintf(report, ['# Closed-loop DPC control-quality comparison\n\n' ...
    'All reported data come from actual converter simulations. ' ...
    'Upper row: Conventional. Lower row: Proposed. No decision plots.\n\n' ...
    'Fs means controller sampling, not fixed semiconductor switching frequency. ' ...
    'THD is harmonic-only percent, orders 2..50 (50 Hz fundamental); DC and interharmonics excluded. ' ...
    'The signal and FFT window are identical in both methods. ' ...
    'A drift flag is a screening check, not proof of complete steady state.\n\n' ...
    '| Fs (kHz) | Method | THD a (%%) | P mean (W) | P pp (W) | Mean f_sw (kHz) | Window steady? |\n' ...
    '|---|---|---|---|---|---|---|\n']);
for k = 1:numel(results)
    r = results{k}; m = r.metrics;
    assert(r.closed_loop_executed && r.simulink_executed);
    values = [r.fft{1}.thd_percent, r.fft{2}.thd_percent, r.fft{3}.thd_percent, ...
        m.p.mean, m.p.peak_to_peak, m.p.ripple_rms, m.p_tracking_rmse, ...
        m.q.mean, m.q.peak_to_peak, m.q.ripple_rms, m.q_tracking_rmse, ...
        m.vdc.mean, m.dc_tracking_error_percent, m.mean_equivalent_switching_hz, ...
        100*m.current_rms_drift_fraction, 100*m.dc_mean_drift_fraction, m.stationary_window];
    fprintf(file, '%.12g,%s', r.info.control_hz, r.info.method);
    fprintf(file, ',%.12g', values); fprintf(file, '\n');
    fprintf(report, '| %g | %s | %.4g | %.4g | %.4g | %.4g | %d |\n', ...
        r.info.control_hz/1000, r.info.method, values(1), m.p.mean, ...
        m.p.peak_to_peak, m.mean_equivalent_switching_hz/1000, m.stationary_window);
end
fprintf(report, ['\nParameters: %s. Proposed variant: %s.\n\n' ...
    'Do not claim improvement from THD alone: check power tracking, DC voltage and ripple together. ' ...
    'If a window is flagged transient, increase stop_time and move fft_start later for BOTH methods.\n'], ...
    results{1}.parameter_note, results{1}.cfg.proposed_variant);
placeholder = fullfile(folder,'GENERATED_AFTER_RUN.txt');
if exist(placeholder,'file'), delete(placeholder); end
end
